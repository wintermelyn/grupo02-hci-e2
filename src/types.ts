/** Open Library work key, e.g. "OL45804W". Used as-is in URLs. */
export type BookId = string
export type ReadingStatus = 'want' | 'owned' | 'reading' | 'read'
/** Calendar date "YYYY-MM-DD" in local time. Build and read it only through src/lib/dates.ts. */
export type ISODate = string

export interface Book {
  id: BookId
  title: string
  authors: string[]
  coverUrl?: string
  description?: string
  /** The description was machine-translated into Spanish, so the page says so. */
  descriptionTranslated?: boolean
  year?: number
  pages?: number
  /** The hex colour of the cover. The 54 books of books.json have it in coverColors.json instead. */
  coverColor?: string
}

export interface LibraryEntry {
  bookId: BookId
  status: ReadingStatus
  folderIds: string[]
  addedAt: ISODate
  /** Last time the person confirmed they still want it; the D5 prompt counts from here, else from addedAt. */
  wantCheckedAt?: ISODate
  startedAt?: ISODate
  finishedAt?: ISODate
  rating?: number
}

export interface Folder {
  id: string
  name: string
  pinned?: boolean
  createdAt: ISODate
}

export interface User {
  id: string
  name: string
  username: string
  avatarColor: string
  mutualFriends: number
  readingIds: BookId[]
  readIds: BookId[]
}

export interface Friendship {
  userId: string
  status: 'pending' | 'friends'
  /** ISO date-time, not a calendar date: the auto-accept timer compares it to the millisecond. */
  since: string
}

export interface Activity {
  id: string
  userId: string
  bookId: BookId
  kind: 'started' | 'finished' | 'want'
  date: ISODate
  rating?: number
}

export interface Toast {
  id: number
  message: string
  undoable: boolean
  /** Deshacer takes the focus when it appears. See focusToast. */
  takesFocus?: boolean
}

export interface AppState {
  /** From the seed, not persisted. */
  me: User
  /** books.json, not persisted. */
  seedBooks: Record<BookId, Book>
  /** Copies of the catalog books the person added, so Mis libros needs no download. Persisted. */
  extraBooks: Record<BookId, Book>
  library: Record<BookId, LibraryEntry>
  folders: Folder[]
  /** users.json, not persisted. */
  users: User[]
  friendships: Friendship[]
  /** Generated by the seed with dates relative to today. */
  activities: Activity[]
  likedActivityIds: string[]
  /** Last day the D5 prompt was answered, persisted. Undoing that answer asks again. */
  lastWantPromptOn?: ISODate
  toast: Toast | null
  /**
   * `friendships` only after removing a friend: a library change must not bring old ones back.
   * `lastWantPromptOn` only after answering the D5 prompt, where undefined is a value to restore.
   */
  undoSnapshot: {
    library: AppState['library']
    folders: Folder[]
    friendships?: Friendship[]
    lastWantPromptOn?: ISODate
  } | null
}
