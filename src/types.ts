/** Open Library work key, e.g. "OL45804W". Used as-is in URLs. */
export type BookId = string
export type ReadingStatus = 'want' | 'reading' | 'read'
/** Calendar date "YYYY-MM-DD" in local time. Build and read it only through src/lib/dates.ts. */
export type ISODate = string

export interface Book {
  id: BookId
  title: string
  authors: string[]
  coverUrl?: string
  description?: string
  year?: number
  pages?: number
}

export interface LibraryEntry {
  bookId: BookId
  status: ReadingStatus
  owned: boolean
  folderIds: string[]
  addedAt: ISODate
  startedAt?: ISODate
  finishedAt?: ISODate
  rating?: number
}

export interface Folder {
  id: string
  name: string
  pinned?: boolean
  createdAt: ISODate
}

export interface User {
  id: string
  name: string
  username: string
  code: string
  avatarColor: string
  mutualFriends: number
  readingIds: BookId[]
  readIds: BookId[]
}

export interface Friendship {
  userId: string
  status: 'pending' | 'friends'
  /** ISO date-time, not a calendar date: the auto-accept timer compares it to the millisecond. */
  since: string
}

export interface Activity {
  id: string
  userId: string
  bookId: BookId
  kind: 'started' | 'finished' | 'want'
  date: ISODate
  rating?: number
}

export interface Toast {
  id: number
  message: string
  undoable: boolean
}

export interface AppState {
  /** From the seed, not persisted. */
  me: User
  /** books.json, not persisted. */
  seedBooks: Record<BookId, Book>
  /** Fetched from the API, persisted. */
  extraBooks: Record<BookId, Book>
  library: Record<BookId, LibraryEntry>
  folders: Folder[]
  /** users.json, not persisted. */
  users: User[]
  friendships: Friendship[]
  /** Generated by the seed with dates relative to today. */
  activities: Activity[]
  likedActivityIds: string[]
  toast: Toast | null
  undoSnapshot: { library: AppState['library']; folders: Folder[] } | null
}
